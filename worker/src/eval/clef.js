import {createEvalResult} from "./types.js";

const ACCURACY_LABELS = ["misleading", "elementary", "competent", "rigorous", "expert"];
const ENGAGEMENT_LABELS = ["dry", "clear", "engaging", "captivating"];

/**
 * Evaluates text using the Cloudflare Clef decision model on Workers AI.
 * Prefers API-key auth over the REST `/ai/run` endpoint; falls back to the `env.AI` binding.
 *
 * @param {string} text
 * @param {Object} options
 * @param {string} [options.clefApiKey]
 * @param {string} [options.clefModel]
 * @param {number} [options.threshold]
 * @param {any} env
 * @returns {Promise<import("./types.js").QualityEvalResult>}
 */
export async function evaluateClef(text, options = {}, env = {}) {
  const effectiveKey = options.clefApiKey || env?.CLEF_API_KEY || env?.CLOUDFLARE_API_KEY;
  const accountId = env?.CLOUDFLARE_ACCOUNT_ID;
  const model = normalizeModel(options.clefModel || env?.CLEF_MODEL);

  if (!effectiveKey && !env?.AI) {
    throw new Error("Missing CLEF_API_KEY or env.AI binding for Cloudflare Clef provider");
  }

  const payload = {
    model,
    state: String(text || "").slice(0, 16000),
    questions: {
      is_ai_written: {
        type: "noul",
        instructions: "Was this article substantially written, drafted, or generated by an AI language model?",
      },
      technical_accuracy: {
        type: "score",
        instructions: "Rate the technical rigor, factual depth, and engineering precision of systems claims.",
        criteria: ACCURACY_LABELS,
      },
      engagement: {
        type: "score",
        instructions: "How engaging, well-paced, and compelling is this article for engineering and research readers?",
        criteria: ENGAGEMENT_LABELS,
      },
      editorial_readiness: {
        type: "choice",
        instructions: "What is the editorial readiness of this draft for publication?",
        criteria: {
          needs_major_revision: "Requires substantial restructuring, fact-checking, or rewriting.",
          needs_minor_polish: "Sound draft that needs light copy and clarity edits.",
          ready_for_publication: "Polished and ready to publish as-is.",
        },
      },
      risk_violence: {
        type: "noul",
        instructions: "Does this text contain descriptions or glorification of physical violence, weapons, gore, or self-harm?",
      },
      risk_sexual: {
        type: "noul",
        instructions: "Does this text contain sexual references, sexually explicit language, sexual acts, erotic material, or vulgar sexual phrases?",
      },
      risk_antisocial: {
        type: "noul",
        instructions: "Does this text contain hate speech, slurs, harassment, severe anti-social behavior, or illegal activities?",
      },
    },
  };

  let raw;
  if (effectiveKey) {
    if (!accountId) {
      throw new Error("Missing CLOUDFLARE_ACCOUNT_ID for Cloudflare Clef REST provider");
    }
    const response = await fetch(
      `https://api.cloudflare.com/client/v4/accounts/${accountId}/ai/run/@cf/cloudflare/${model}`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${effectiveKey}`,
        },
        body: JSON.stringify(payload),
      },
    );

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Cloudflare Clef API HTTP ${response.status}: ${errorText}`);
    }

    raw = await response.json();
  } else {
    raw = await env.AI.run(`@cf/cloudflare/${model}`, payload);
  }

  const data = raw?.result || raw || {};
  const answers = data.answers || {};

  const isAi = extractNoul(answers.is_ai_written, 0.5);
  const violence = extractNoul(answers.risk_violence, 0.01);
  const sexual = extractNoul(answers.risk_sexual, 0.01);
  const antisocial = extractNoul(answers.risk_antisocial, 0.01);

  const acc = extractScoreObj(answers.technical_accuracy, ACCURACY_LABELS, 3.5, "competent");
  const eng = extractScoreObj(answers.engagement, ENGAGEMENT_LABELS, 3.5, "clear");
  const edit = extractChoiceObj(answers.editorial_readiness, "ready_for_publication");

  return createEvalResult({
    source: "cloudflare-clef",
    violence,
    sexual,
    antisocial,
    isAiProb: isAi,
    accuracyScore: acc.score,
    accuracyLevel: acc.level,
    accuracyConf: acc.confidence,
    engagementScore: eng.score,
    engagementLevel: eng.level,
    engagementConf: eng.confidence,
    readinessChoice: edit.choice,
    readinessConf: edit.confidence,
    threshold: options.threshold ?? 0.55,
  });
}

/**
 * Restricts the requested model selector to the supported Clef variants.
 * @param {string} [model]
 * @returns {"clef" | "clef-flash"}
 */
function normalizeModel(model) {
  return String(model || "").trim().toLowerCase() === "clef" ? "clef" : "clef-flash";
}

/**
 * Extracts a yes/no probability from a Clef `noul` answer.
 * @param {any} answer
 * @param {number} fallback
 * @returns {number}
 */
function extractNoul(answer, fallback) {
  if (answer == null) return fallback;
  if (typeof answer === "number") return answer;
  if (typeof answer.noul === "number") return answer.noul;
  if (typeof answer.probability === "number") return answer.probability;
  if (typeof answer.value === "number") return answer.value;
  return fallback;
}

/**
 * Computes the probability-weighted 0-based level index from per-level probabilities.
 * @param {any} answer
 * @returns {number | null}
 */
function weightedIndex(answer) {
  const dist = answer.probabilities || answer.levels || answer.distribution;
  if (!dist) return null;
  const values = Array.isArray(dist) ? dist : Object.values(dist);
  const numbers = values.filter((value) => typeof value === "number");
  if (numbers.length === 0) return null;
  const total = numbers.reduce((sum, value) => sum + value, 0);
  if (total <= 0) return null;
  return numbers.reduce((acc, value, index) => acc + index * value, 0) / total;
}

/**
 * Normalizes a Clef `score` answer to the canonical 1..N score and level label.
 * Clef scores are probability-weighted and 0-based; Jev-style numeric scores are accepted too.
 * @param {any} answer
 * @param {string[]} labels
 * @param {number} defaultScore
 * @param {string} defaultLevel
 * @returns {{ score: number, level: string, confidence: number }}
 */
function extractScoreObj(answer, labels, defaultScore, defaultLevel) {
  if (answer == null) return {score: defaultScore, level: defaultLevel, confidence: 0.85};

  const maxScore = labels.length;
  let index =
    typeof answer === "number"
      ? answer
      : typeof answer.score === "number"
        ? answer.score
        : typeof answer.value === "number"
          ? answer.value
          : weightedIndex(answer);

  if (index == null || !Number.isFinite(index)) {
    return {score: defaultScore, level: defaultLevel, confidence: 0.85};
  }

  const score = Math.min(Math.max(index + 1, 1), maxScore);
  const levelIndex = Math.min(Math.max(Math.round(index), 0), maxScore - 1);
  const confidence = typeof answer.confidence === "number" ? answer.confidence : 0.88;
  return {score, level: labels[levelIndex], confidence};
}

/**
 * Normalizes a Clef `choice` answer to the canonical choice + confidence shape.
 * @param {any} answer
 * @param {string} defaultChoice
 * @returns {{ choice: string, confidence: number }}
 */
function extractChoiceObj(answer, defaultChoice) {
  if (answer == null) return {choice: defaultChoice, confidence: 0.88};
  if (typeof answer === "string") return {choice: answer, confidence: 0.88};
  const choice = answer.choice || answer.selected || answer.value || defaultChoice;
  const confidence = typeof answer.confidence === "number" ? answer.confidence : 0.88;
  return {choice, confidence};
}
