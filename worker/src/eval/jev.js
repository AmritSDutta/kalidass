import {createEvalResult} from "./types.js";

const ACCURACY_LABELS = ["misleading", "elementary", "competent", "rigorous", "expert"];
const ENGAGEMENT_LABELS = ["dry", "clear", "engaging", "captivating"];
const EDITORIAL_CRITERIA = {
  needs_major_revision: "Requires substantial restructuring, fact-checking, or rewriting.",
  needs_minor_polish: "Sound draft that needs light copy and clarity edits.",
  ready_for_publication: "Polished and ready to publish as-is.",
};

/**
 * Evaluates text using the TypeSafe AI Jev System One decision model.
 * @param {string} text
 * @param {Object} options
 * @param {string} [options.apiKey]
 * @param {number} [options.threshold]
 * @param {any} env
 * @returns {Promise<import("./types.js").QualityEvalResult>}
 */
export async function evaluateJev(text, options = {}, env = {}) {
  const effectiveKey = options.apiKey || env?.TYPESAFE_API_KEY || env?.JEV_API_KEY;
  if (!effectiveKey) {
    throw new Error("Missing TYPESAFE_API_KEY for Jev provider");
  }

  const payload = {
    model: "jev-latest",
    state: String(text || "").slice(0, 16000),
    questions: {
      is_ai_written: {
        type: "noul",
        instructions: "Was this article substantially written, drafted, or generated by an AI language model?",
      },
      technical_accuracy: {
        type: "score",
        instructions: "Rate the technical rigor, factual depth, and engineering precision of systems claims.",
        criteria: ACCURACY_LABELS,
      },
      engagement: {
        type: "score",
        instructions: "How engaging, well-paced, and compelling is this article for engineering and research readers?",
        criteria: ENGAGEMENT_LABELS,
      },
      editorial_readiness: {
        type: "choice",
        instructions: "What is the editorial readiness of this draft for publication?",
        criteria: EDITORIAL_CRITERIA,
      },
      risk_violence: {
        type: "noul",
        instructions: "Does this text contain descriptions or glorification of physical violence, weapons, gore, or self-harm?",
      },
      risk_sexual: {
        type: "noul",
        instructions: "Does this text contain sexual references, sexually explicit language, sexual acts, erotic material, or vulgar sexual phrases?",
      },
      risk_antisocial: {
        type: "noul",
        instructions: "Does this text contain hate speech, slurs, harassment, severe anti-social behavior, or illegal activities?",
      },
    },
  };

  console.log(`[TypeSafe Jev] Calling System One (${payload.model}) with ${Object.keys(payload.questions).length} questions...`);

  const response = await fetch("https://api.typesafe.ai/v1/systemone", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${effectiveKey}`,
    },
    body: JSON.stringify(payload),
  });

  if (!response.ok) {
    const errorText = await response.text();
    console.error(`[TypeSafe Jev] API error HTTP ${response.status}: ${errorText}`);
    throw new Error(`TypeSafe Jev API HTTP ${response.status}: ${errorText}`);
  }

  const raw = await response.json();
  console.log(`[TypeSafe Jev] System One call succeeded (model: ${raw.model || "jev"})`);
  const data = raw.results || raw.answers || raw;

  const extractNoulVal = (item, fallback = 0.01) => {
    if (typeof item === "number") return item;
    if (item && typeof item.noul === "number") return item.noul;
    if (item && typeof item.probability === "number") return item.probability;
    if (item && typeof item.value === "number") return item.value;
    return fallback;
  };

  const isAi = extractNoulVal(data.is_ai_written, 0.5);
  const violence = extractNoulVal(data.risk_violence, 0.01);
  const sexual = extractNoulVal(data.risk_sexual, 0.01);
  const antisocial = extractNoulVal(data.risk_antisocial, 0.01);

  const extractScoreObj = (item, defaultScore = 3.5, defaultLevel = "competent") => {
    if (!item) return {score: defaultScore, level: defaultLevel, confidence: 0.85};
    if (typeof item === "number") return {score: item, level: defaultLevel, confidence: 0.85};
    const score = typeof item.score === "number" ? item.score : defaultScore;
    const level = item.level || item.legend || item.choice || defaultLevel;
    const confidence = typeof item.confidence === "number" ? item.confidence : 0.88;
    return {score, level, confidence};
  };

  const extractChoiceObj = (item, defaultChoice = "ready_for_publication") => {
    if (!item) return {choice: defaultChoice, confidence: 0.88};
    if (typeof item === "string") return {choice: item, confidence: 0.88};
    const choice = item.choice || item.selected || defaultChoice;
    const confidence = typeof item.confidence === "number" ? item.confidence : 0.88;
    return {choice, confidence};
  };

  const acc = extractScoreObj(data.technical_accuracy, 3.5, "competent");
  const eng = extractScoreObj(data.engagement, 3.5, "clear");
  const edit = extractChoiceObj(data.editorial_readiness, "ready_for_publication");

  return createEvalResult({
    source: "typesafe-jev",
    violence,
    sexual,
    antisocial,
    isAiProb: isAi,
    accuracyScore: acc.score,
    accuracyLevel: acc.level,
    accuracyConf: acc.confidence,
    engagementScore: eng.score,
    engagementLevel: eng.level,
    engagementConf: eng.confidence,
    readinessChoice: edit.choice,
    readinessConf: edit.confidence,
    threshold: options.threshold ?? 0.55,
  });
}
